const module = "github.com/rambow-cloud/alicloud-go-sdk-x"

// Render produces the entire owned file set without touching the filesystem.
func Render(p Product) (map[string][]byte, error) {
	files := map[string][]byte{}
	base := "services/" + p.Manifest.Package + "/"
	code, err := emitClient(p)
	if err != nil {
		return nil, err
	}
	files[base+"sdk.gen.go"] = code
	code, err = emitExamples(p)
	if err != nil {
		return nil, err
	}
	files[base+"examples.gen_test.go"] = code
	var doc strings.Builder
	doc.WriteString(generated)
	doc.WriteString("\n")
	fmt.Fprintf(&doc, "// Package %s %s\npackage %s\n", p.Manifest.Package, lowerFirst(p.Overlay.Doc.English), p.Manifest.Package)
	code, err = format.Source([]byte(doc.String()))
	if err != nil {
		return nil, err
	}
	files[base+"doc.go"] = code
	if len(p.Overlay.paginatorSpecs()) > 0 || len(p.Overlay.waiterSpecs()) > 0 {
		code, err = emitAdapters(p)
		if err != nil {
			return nil, err
		}
		files[base+"adapters.gen.go"] = code
	}
	files["docs/generated/"+p.Manifest.Package+".md"] = emitGuide(p)
	return files, nil
}

func lowerFirst(s string) string {
	if len(s) == 0 {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}
func quote(s string) string { return strconv.Quote(s) }

func preamble(b *bytes.Buffer, pkg string, imports map[string]string) {
	b.WriteString(generated)
	fmt.Fprintf(b, "package %s\n\nimport (\n", pkg)
	for _, path := range sortedKeys(imports) {
		fmt.Fprintf(b, "%s %q\n", imports[path], path)
	}
	b.WriteString(")\n\n")
}

