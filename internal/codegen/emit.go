func copySlices(b *bytes.Buffer, fields []Field, dst, src string, models ...[]Model) {
	for _, f := range fields {
		if f.Type == "[]string" {
			fmt.Fprintf(b, "%s.%s=append([]string(nil),%s.%s...)\n", dst, f.Name, src, f.Name)
		}
		if strings.HasPrefix(f.Type, "*") {
			fmt.Fprintf(b, "if %s.%s!=nil{copied:=*%s.%s;%s.%s=&copied}\n", src, f.Name, src, f.Name, dst, f.Name)
		}
		if strings.HasPrefix(f.Type, "[]") && f.Type != "[]string" && len(models) > 0 {
			for _, m := range models[0] {
				if m.Name == strings.TrimPrefix(f.Type, "[]") && m.Location == "input" {
					fmt.Fprintf(b, "%s.%s=append([]%s(nil),%s.%s...)\nfor i:=range %s.%s{%s.%s[i]=clone%s(%s.%s[i])}\n", dst, f.Name, m.Name, src, f.Name, dst, f.Name, dst, f.Name, m.Name, dst, f.Name)
				}
			}
		}
	}
}

type wireNode struct {
	typ      string
	children map[string]*wireNode
	goName   string
}

func wireTree(fields []Field) *wireNode {
	root := &wireNode{children: map[string]*wireNode{}}
	for _, f := range fields {
		node := root
		for _, part := range strings.Split(f.Wire, ".") {
			if node.children == nil {
				node.children = map[string]*wireNode{}
			}
			if node.children[part] == nil {
				node.children[part] = &wireNode{}
			}
			node = node.children[part]
		}
		node.typ = f.Type
	}
	return root
}
func emitWire(b *bytes.Buffer, node *wireNode) {
	b.WriteString("struct {\n")
	for i, key := range sortedKeys(node.children) {
		child := node.children[key]
		child.goName = "W" + strconv.Itoa(i)
		fmt.Fprintf(b, "%s ", child.goName)
		if child.typ != "" {
			b.WriteString(child.typ)
		} else {
			emitWire(b, child)
		}
		fmt.Fprintf(b, " `json:%s`\n", quote(key))
	}
	b.WriteString("}")
}
func wireAccess(root *wireNode, path string) string {
	value := "wire"
	for _, part := range strings.Split(path, ".") {
		root = root.children[part]
		value += "." + root.goName
	}
	return value
}

func emitOperation(b *bytes.Buffer, p Product, op Operation) error {
	fmt.Fprintf(b, "// %s %s\n// API version %s. Errors preserve cancellation and structured service causes.\n", op.Name, lowerFirst(op.Doc.English), p.Manifest.Version)
	if !*op.Idempotent {
		b.WriteString("// This operation is conservatively non-idempotent and is not retried by Standard.\n")
	}
	fmt.Fprintf(b, "func(c *Client)%s(ctx context.Context,input *%sInput,opts ...func(*Options))(*%sOutput,error){\n", op.Name, op.Name, op.Name)
	fmt.Fprintf(b, "fail:=func(err error)(*%sOutput,error){return nil,generatedValidation(ctx,%q,err)}\n", op.Name, op.Name)
	b.WriteString("if err:=ctx.Err();err!=nil{return fail(err)}\n")
	if op.InputRequired {
		b.WriteString("if input==nil{return fail(errors.New(\"input required\"))}\n")
	}
	fmt.Fprintf(b, "var in %sInput\nif input!=nil{in=*input\n", op.Name)
	copySlices(b, op.Inputs, "in", "input", p.Models)
	b.WriteString("}\n")
	b.WriteString("requestRegion:=\"\"\n")
	for _, f := range op.Inputs {
		if f.Region {
			fmt.Fprintf(b, "requestRegion=in.%s\n", f.Name)
		}
	}
	b.WriteString("callOptions,err:=c.callOptions(requestRegion,opts);if err!=nil{return fail(err)}\n")
	fmt.Fprintf(b, "codec:=alicloud.Codec{Encode:func(ctx context.Context,value any)(alicloud.Request,error){in:=*value.(*%sInput)\n", op.Name)
	copySlices(b, op.Inputs, "in", "in", p.Models)
	b.WriteString("fail:=func(err error)(alicloud.Request,error){return alicloud.Request{},err}\n_ = fail\n")
	if op.Validator != "" {
		fmt.Fprintf(b, "if err:=%s(in);err!=nil{return fail(err)}\n", op.Validator)
	}
	b.WriteString("region:=\"\"\nq:=url.Values{}\n")
	for _, f := range op.Inputs {
		value := "in." + f.Name
		if f.Region {
			fmt.Fprintf(b, "region=%s;if region==\"\"{region=c.runtime.Region()};q.Set(%q,region)\n", value, f.Wire)
			continue
		}
		if !strings.HasPrefix(f.Type, "[]") {
			emitQueryField(b, f, value, quote(f.Wire))
			continue
		}
		if f.Required {
			fmt.Fprintf(b, "if len(%s)==0{return fail(errors.New(%q))}\n", value, "required parameter "+f.Wire)
		}
		if f.MaxItems > 0 {
			fmt.Fprintf(b, "if len(%s)>%d{return fail(errors.New(%q))}\n", value, f.MaxItems, "array too large: "+f.Wire)
		}
		if f.Type == "[]string" {
			if f.Encoding == "jsonArray" {
				fmt.Fprintf(b, "if len(%s)>0{encoded,err:=json.Marshal(%s);if err!=nil{return fail(err)};q.Set(%q,string(encoded))}\n", value, value, f.Wire)
			} else {
				fmt.Fprintf(b, "for i,value:=range %s{q.Set(%q+strconv.Itoa(i+1),value)}\n", value, f.Wire+".")
			}
		} else {
			for _, m := range p.Models {
				if m.Name == strings.TrimPrefix(f.Type, "[]") {
					fmt.Fprintf(b, "for i,item:=range %s{prefix:=%q+strconv.Itoa(i+1)+\".\"\n", value, f.Wire+".")
					for _, member := range m.Fields {
						emitQueryField(b, member, "item."+member.Name, "prefix+"+quote(member.Wire))
					}
					b.WriteString("}\n")
				}
			}
		}
	}
	method, path := "POST", "/"
	if op.Protocol.Method != "" {
		method, path = op.Protocol.Method, op.Protocol.Path
	}
	fmt.Fprintf(b, "return alicloud.Request{Method:%q,Path:%q,Region:region,Query:q,Header:map[string][]string{\"Content-Type\":{\"application/x-www-form-urlencoded\"}}},nil},Decode:func(ctx context.Context,data []byte,value any)error{\n", method, path)
	root := wireTree(op.Outputs)
	b.WriteString("var wire ")
	emitWire(b, root)
	b.WriteString("\nif err:=json.Unmarshal(data,&wire);err!=nil{return err}\n")
	fmt.Fprintf(b, "*value.(*%sOutput)=%sOutput{", op.Name, op.Name)
	for _, f := range op.Outputs {
		fmt.Fprintf(b, "%s:%s,", f.Name, wireAccess(root, f.Wire))
	}
	b.WriteString("};return nil}}\n")
	action, version := op.Name, p.Manifest.Version
	if op.Protocol.Action != "" {
		action, version = op.Protocol.Action, op.Protocol.Version
	}
	fmt.Fprintf(b, "out:=new(%sOutput)\nmeta,err:=c.runtime.InvokeModel(ctx,alicloud.Operation{Service:%q,Name:%q,Version:%q,Idempotent:%t},&in,alicloud.Request{Region:requestRegion},out,codec,callOptions...)\nif err!=nil{return nil,err};out.Metadata=meta;return out,nil\n}\n", op.Name, p.Manifest.Service, action, version, *op.Idempotent)
	return nil
}

func emitExamples(p Product) ([]byte, error) {
	var b bytes.Buffer
	preamble(&b, p.Manifest.Package+"_test", map[string]string{"context": "", "fmt": "", "net/http": "", module: "alicloud", module + "/credentials": "", module + "/sdktest": "", module + "/services/" + p.Manifest.Package: ""})
	for _, op := range p.Operations {
		fmt.Fprintf(&b, "func ExampleClient_%s_generated(){\n", op.Name)
		b.WriteString("provider,err:=credentials.NewStaticProvider(credentials.Credentials{AccessKeyID:\"placeholder\",AccessKeySecret:\"placeholder\"});if err!=nil{panic(err)}\n")
		fmt.Fprintf(&b, "transport:=sdktest.NewTransport(sdktest.Step{Body:%q})\n", op.Example.Response)
		fmt.Fprintf(&b, "client,err:=%s.New(alicloud.Config{Region:\"cn-hangzhou\",BaseEndpoint:\"https://example.invalid\",CredentialsProvider:provider,HTTPClient:&http.Client{Transport:transport}});if err!=nil{panic(err)}\n", p.Manifest.Package)
		fmt.Fprintf(&b, "out,err:=client.%s(context.Background(),&%s.%sInput{", op.Name, p.Manifest.Package, op.Name)
		for _, name := range sortedKeys(op.Example.Input) {
			fmt.Fprintf(&b, "%s:", name)
			fields := map[string]Field{}
			for _, f := range op.Inputs {
				fields[f.Name] = f
			}
			models := map[string]ModelSpec{}
			for _, m := range p.Models {
				models[m.Name] = m.ModelSpec
			}
			literal, err := exampleLiteral(fields[name].Type, op.Example.Input[name], p.Manifest.Package, models)
			if err != nil {
				return nil, err
			}
			b.WriteString(literal)
			b.WriteString(",")
		}
		fmt.Fprintf(&b, "});if err!=nil{panic(err)}\nfmt.Println(out.%s)\n// Output: %s\n}\n", op.Example.Print, op.Example.Output)
	}
	return format.Source(b.Bytes())
}

